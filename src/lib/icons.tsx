/** Get the Lucide icon component for a product by name */
export function getProductIcon(name: string): LucideIcon {
  const iconName = PRODUCT_ICONS[name];
  return iconName ? getIcon(iconName) : FALLBACK_ICON;
}

/** Get the icon for a product, falling back to its category icon if not found */
export function getProductOrCategoryIcon(name: string, category: string): LucideIcon {
  const iconName = PRODUCT_ICONS[name];
  if (iconName) return getIcon(iconName);
  return getCategoryIcon(category);
}
