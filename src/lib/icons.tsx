/** Fallback icon when nothing matches */
export const FALLBACK_ICON: LucideIcon = Package;

/**
 * Resolve an icon by name, returning the Lucide component.
 */
export function getIcon(name: string): LucideIcon {
  return ICON_REGISTRY[name] ?? FALLBACK_ICON;
}

